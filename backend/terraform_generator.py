import json
import re
from typing import Any


SUPPORTED_PROVIDERS = {"aws", "gcp", "azure"}


def generate_files(configuration: dict[str, Any]) -> dict[str, str]:
    provider = configuration.get("provider")
    if provider not in SUPPORTED_PROVIDERS:
        raise ValueError("Provider must be aws, gcp, or azure")
    values = _values(configuration, provider)
    renderers = {
        "aws": _aws_files,
        "gcp": _gcp_files,
        "azure": _azure_files,
    }
    return renderers[provider](values)


def preview(configuration: dict[str, Any]) -> dict[str, Any]:
    return {
        "mode": "local-preview",
        "backend": "disabled",
        "provider": configuration.get("provider"),
        "files": generate_files(configuration),
        "message": "Generated locally. Terraform was not initialized, planned, or applied.",
    }


def _values(configuration: dict[str, Any], provider: str) -> dict[str, Any]:
    project_name = _safe_name(str(configuration.get("project_name", "cloudpilot")))
    defaults = {
        "aws": ("t3.micro", ""),
        "gcp": ("e2-medium", "ubuntu-os-cloud/ubuntu-2204-lts"),
        "azure": ("Standard_B1s", "Canonical", "0001-com-ubuntu-server-jammy", "22_04-lts-gen2"),
    }
    values: dict[str, Any] = {
        "project_name": project_name,
        "region": str(configuration.get("region", "")),
        "vm_count": int(configuration.get("vm_count", 1)),
        "machine_type": configuration.get("machine_type", defaults[provider][0]),
        "vpc_cidr": str(configuration.get("vpc_cidr", "10.0.0.0/16")),
        "storage_gb": int(configuration.get("storage_gb", 50)),
        "database_enabled": bool(configuration.get("database_enabled", False)),
    }
    if provider == "aws":
        values["ami_id"] = configuration.get("ami_id", defaults["aws"][1])
    if provider == "azure":
        values.update(
            {
                "publisher": configuration.get("image_publisher", defaults["azure"][1]),
                "offer": configuration.get("image_offer", defaults["azure"][2]),
                "sku": configuration.get("image_sku", defaults["azure"][3]),
            }
        )
    return values


def _common_variables(values: dict[str, Any], extra: str = "") -> str:
    return f'''variable "project_name" {{
  type    = string
  default = "{values["project_name"]}"
}}

variable "region" {{
  type = string
}}

variable "vm_count" {{
  type    = number
  default = {values["vm_count"]}
  validation {{
    condition     = var.vm_count >= 1 && var.vm_count <= 100
    error_message = "vm_count must be between 1 and 100."
  }}
}}

variable "machine_type" {{
  type    = string
  default = "{values["machine_type"]}"
}}

variable "vpc_cidr" {{
  type    = string
  default = "{values["vpc_cidr"]}"
}}

variable "storage_gb" {{
  type    = number
  default = {values["storage_gb"]}
}}

{extra}'''


def _aws_files(values: dict[str, Any]) -> dict[str, str]:
    database = '''
variable "database_password" {
  type      = string
  sensitive = true
}
'''
    database_resource = '''
resource "aws_db_instance" "cloudpilot" {
  count                  = var.database_enabled ? 1 : 0
  allocated_storage      = var.storage_gb
  engine                 = "postgres"
  engine_version         = "16"
  instance_class         = "db.t3.micro"
  db_name                = "cloudpilot"
  username               = "cloudpilot"
  password               = var.database_password
  skip_final_snapshot    = true
  publicly_accessible    = false
  db_subnet_group_name   = aws_db_subnet_group.cloudpilot[0].name
  vpc_security_group_ids = [aws_security_group.cloudpilot.id]
}

resource "aws_db_subnet_group" "cloudpilot" {
  count      = var.database_enabled ? 1 : 0
  name       = "${var.project_name}-db"
  subnet_ids = [aws_subnet.private.id]
}
'''
    main = f'''# Generated by CloudPilot.
# Provider-valid preview only; no Terraform command or cloud API is executed.
terraform {{
  required_providers {{
    aws = {{
      source  = "hashicorp/aws"
      version = "~> 5.0"
    }}
  }}
}}

provider "aws" {{
  region = var.region
}}

resource "aws_vpc" "cloudpilot" {{
  cidr_block           = var.vpc_cidr
  enable_dns_hostnames = true
  enable_dns_support   = true
  tags = {{ Name = var.project_name }}
}}

resource "aws_subnet" "private" {{
  vpc_id            = aws_vpc.cloudpilot.id
  cidr_block        = cidrsubnet(var.vpc_cidr, 8, 1)
  availability_zone = "${{var.region}}a"
  tags = {{ Name = "${{var.project_name}}-private" }}
}}

resource "aws_security_group" "cloudpilot" {{
  name   = "${{var.project_name}}-internal"
  vpc_id = aws_vpc.cloudpilot.id
  ingress {{
    protocol    = "-1"
    from_port   = 0
    to_port     = 0
    cidr_blocks = [var.vpc_cidr]
  }}
  egress {{
    protocol    = "-1"
    from_port   = 0
    to_port     = 0
    cidr_blocks = ["0.0.0.0/0"]
  }}
}}

resource "aws_instance" "cloudpilot" {{
  count                       = var.vm_count
  ami                         = var.ami_id
  instance_type               = var.machine_type
  subnet_id                   = aws_subnet.private.id
  vpc_security_group_ids      = [aws_security_group.cloudpilot.id]
  associate_public_ip_address = false
  tags = {{ Name = "${{var.project_name}}-${{count.index + 1}}" }}
}}

{database_resource if values["database_enabled"] else ""}
'''
    variables = _common_variables(
        values,
        f'''        variable "ami_id" {{
          type    = string
        }}

variable "database_enabled" {{
  type    = bool
  default = {str(values["database_enabled"]).lower()}
}}
{database}''',
    )
    return _files(main, variables, values, "aws")


