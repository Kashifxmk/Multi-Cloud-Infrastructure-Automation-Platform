from pathlib import Path
from typing import Any


SUPPORTED_PROVIDERS = {"aws", "gcp", "azure"}


def generate_files(configuration: dict[str, Any]) -> dict[str, str]:
    provider = configuration.get("provider")
    if provider not in SUPPORTED_PROVIDERS:
        raise ValueError("Provider must be aws, gcp, or azure")
    region = configuration.get("region", "")
    vm_count = int(configuration.get("vm_count", 1))
    machine_type = configuration.get("machine_type", "e2-medium")
    vpc_cidr = configuration.get("vpc_cidr", "10.0.0.0/16")
    provider_block = {
        "aws": f'provider "aws" {{\n  region = var.region\n}}',
        "gcp": f'provider "google" {{\n  region = var.region\n}}',
        "azure": 'provider "azurerm" {\n  features {}\n}',
    }[provider]
    resource_type = {"aws": "aws_instance", "gcp": "google_compute_instance", "azure": "azurerm_linux_virtual_machine"}[provider]
    resource = f'''resource "{resource_type}" "cloudpilot" {{
  count = var.vm_count
  # Preview-only resource definition; apply is intentionally not executed.
  name = "${{var.project_name}}-${{count.index + 1}}"
  machine_type = var.machine_type
  network_cidr = var.vpc_cidr
}}'''
    if provider == "azure":
        resource = f'''resource "{resource_type}" "cloudpilot" {{
  count = var.vm_count
  name = "${{var.project_name}}-${{count.index + 1}}"
  size = var.machine_type
  location = var.region
}}'''
    return {
        "main.tf": f'''# Generated by CloudPilot local MVP.
# This file is a preview and is not connected to a cloud account.
{provider_block}

{resource}
''',
        "variables.tf": '''variable "project_name" {
  type    = string
  default = "cloudpilot"
}

variable "region" {
  type = string
}

variable "vm_count" {
  type    = number
  default = 1
  validation {
    condition     = var.vm_count >= 1 && var.vm_count <= 100
    error_message = "vm_count must be between 1 and 100."
  }
}

variable "machine_type" {
  type = string
}

variable "vpc_cidr" {
  type = string
}
''',
        "outputs.tf": '''output "provider" {
  value = "''' + provider + '''"
}

output "region" {
  value = var.region
}

output "resource_count" {
  value = var.vm_count
}
''',
        "terraform.tfvars.example": f'''project_name = "cloudpilot"
region      = "{region}"
vm_count    = {vm_count}
machine_type = "{machine_type}"
vpc_cidr     = "{vpc_cidr}"
''',
    }


def preview(configuration: dict[str, Any]) -> dict[str, Any]:
    return {
        "mode": "local-preview",
        "backend": "disabled",
        "provider": configuration.get("provider"),
        "files": generate_files(configuration),
        "message": "Generated locally. Terraform was not initialized, planned, or applied.",
    }
