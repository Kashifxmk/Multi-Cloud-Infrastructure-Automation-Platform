def _files(main: str, variables: str, values: dict[str, Any], provider: str) -> dict[str, str]:
    return {
        "main.tf": main,
        "variables.tf": variables,
        "outputs.tf": f'''output "provider" {{
  value = "{provider}"
}}

output "region" {{
  value = var.region
}}

output "resource_count" {{
  value = var.vm_count
}}
''',
        "terraform.tfvars.example": "\n".join(
            [
                f"project_name = {json.dumps(values['project_name'])}",
                f"region = {json.dumps(values['region'])}",
                f"vm_count = {values['vm_count']}",
                f"machine_type = {json.dumps(values['machine_type'])}",
                f"vpc_cidr = {json.dumps(values['vpc_cidr'])}",
                f"storage_gb = {values['storage_gb']}",
                f"database_enabled = {str(values['database_enabled']).lower()}",
                *(
                    ['ami_id = ""']
                    if provider == "aws"
                    else ['ssh_public_key = ""']
                    if provider == "azure"
                    else []
                ),
                '# Set database_password through a secret manager when database_enabled = true.',
            ]
        )
        + "\n",
    }


def _safe_name(value: str) -> str:
    normalized = re.sub(r"[^a-zA-Z0-9-]", "-", value).strip("-").lower()
    return normalized or "cloudpilot"
